import type { FileDiff, Hunk, MechanicalInfo } from "../core/types.js";
import { basename } from "../core/paths.js";

const LOCKFILES = new Set([
  "package-lock.json",
  "npm-shrinkwrap.json",
  "yarn.lock",
  "pnpm-lock.yaml",
  "bun.lockb",
  "Cargo.lock",
  "Gemfile.lock",
  "poetry.lock",
  "Pipfile.lock",
  "composer.lock",
  "go.sum",
  "packages.lock.json",
]);

const GENERATED_PATH = [/(^|\/)generated\//, /\.generated\.\w+$/, /\.g\.\w+$/, /\.min\.(js|css)$/, /(^|\/)dist\//, /\.pb\.\w+$/];
const GENERATED_MARKER = /@generated|DO NOT EDIT|auto-?generated|Code generated by/i;

/** Matches `"name": "^1.2.3",` style dependency lines in package manifests. */
const DEP_LINE = /^\s*"[^"]+"\s*:\s*"[~^>=<]*\s*\d[\w.\-+]*"\s*,?\s*$/;

export interface MechanicalContext {
  /** True if any lockfile changed in this PR (turns dependency-only manifest edits mechanical). */
  lockfileChanged: boolean;
  /** First lines of the file (either side), for generated-file markers. */
  head: string;
}

export function prHasLockfileChange(files: FileDiff[]): boolean {
  return files.some((f) => LOCKFILES.has(basename(f.path)));
}

export function detectMechanical(file: FileDiff, hunk: Hunk, ctx: MechanicalContext): MechanicalInfo | null {
  const name = basename(file.path);
  if (LOCKFILES.has(name)) return { kind: "lockfile", reason: `${name} is a lockfile` };
  if (file.binary) return { kind: "binary", reason: "binary file" };
  if (GENERATED_PATH.some((re) => re.test(file.path)) || GENERATED_MARKER.test(ctx.head)) {
    return { kind: "generated", reason: "generated file (path or header marker)" };
  }
  if (file.status === "renamed" && !hunk.header) {
    return { kind: "rename", reason: `pure rename from ${file.oldPath} (${file.similarity ?? 100}% similar)` };
  }
  const changed = hunk.lines.filter((l) => l.kind !== "ctx");
  if (changed.length > 0) {
    const squash = (kind: "add" | "del") =>
      changed
        .filter((l) => l.kind === kind)
        .map((l) => l.text)
        .join("")
        .replace(/\s+/g, "");
    if (squash("add") === squash("del")) return { kind: "whitespace", reason: "whitespace-only change" };
  }
  if (name === "package.json" && ctx.lockfileChanged && changed.length > 0 && changed.every((l) => DEP_LINE.test(l.text))) {
    return { kind: "dependency-manifest", reason: "dependency version bump alongside a lockfile change" };
  }
  return null;
}
